import Image from 'next/image';
import styles from './ArtworkFrame.module.css';

/**
 * A painting hung inside a fixed-size frame.
 *
 * This component carries the project's hard layout rule: **a painting is never
 * cropped.** The frame is a fixed box at a single aspect ratio, shared by every
 * card, which is what keeps grid rows aligned. The painting sits inside it at
 * its own natural ratio, scaled down to fit entirely, centred, with padding on
 * all sides — so a tall portrait and a wide landscape occupy identical boxes
 * while both stay whole.
 *
 * The mechanism is a size container on the mat and a box inside it at the
 * painting's own ratio, as large as fits in both axes (plus `object-fit:
 * contain` as a backstop), in ArtworkFrame.module.css. Do not replace it with
 * `object-fit: cover` or a fixed `fill` layout — both crop.
 *
 * `image.width` / `image.height` are the true pixel dimensions of the file,
 * generated by scripts/generate-image-manifest.mjs, never typed by hand.
 */
export default function ArtworkFrame({
  image,
  alt,
  sizes,
  priority = false,
  ratio,
  /**
   * Shown in place of the painting when there is no image yet.
   *
   * A work is created in the admin before its photograph is attached — she
   * enters the details, then adds the picture — so "no image" is a normal
   * state of a real record, not an error. The frame still reserves its box, so
   * a grid containing one does not go ragged, and the label says which state
   * this is rather than leaving a silent empty rectangle.
   *
   * Without this the card crashed: `image.src` on an undefined image.
   */
  emptyLabel,
  /**
   * "surface" mounts the work on a near-white board; "bare" hangs it straight
   * on the wall.
   *
   * The rule the mount serves is not "every painting has a mount" — it is that
   * a painting must never meet the warm wall at small scale without
   * separation. Many small works in a grid are warm on warm and each needs its
   * own edge, which the mount gives them. One large work alone holds the wall
   * by itself and its edges sit far enough apart that the ground barely
   * touches it; a mount there would read as a card, and a card reads as
   * commerce rather than gallery.
   *
   * So "bare" is a described exception, not an inconsistency, and it is
   * conditional: with no mount the shadow does the separating, which is why
   * the bare tone carries --shadow-frame-bare. See images.md.
   *
   * "snug" is the wall's: no shared box, the painting at its own ratio on a
   * thin board. The mount rule still holds — the board is there, only as wide
   * as a real mount — and it is still never cropped.
   */
  tone = 'surface',
  className = '',
}) {
  /* "snug" takes the painting's own ratio, so with no painting it falls back
     to the shared box rather than collapsing to a strip of mount. */
  const snugEmpty = tone === 'snug' && !image ? styles.snugEmpty : '';

  return (
    <div
      className={[styles.frame, styles[tone], snugEmpty, className].filter(Boolean).join(' ')}
      /* Lets the hero opt into a wider frame without a second component. */
      style={ratio ? { '--frame-ratio': ratio } : undefined}
    >
      {/*
        The painting is centred inside an absolutely-positioned mat rather than
        laid out in normal flow. That matters: in flow, the image's intrinsic
        height wins over the frame's aspect-ratio and stretches the box, so
        cards end up different heights. Taking it out of flow makes the frame's
        height definite, which is what "fixed-size container" requires.
      */}
      <div className={styles.mat}>
        {image ? (
          /*
            The box the painting hangs in, sized from the file's own ratio
            before a byte of the file has arrived. The image alone cannot do
            this: at `width: auto` it is 0x0 until the browser knows its
            intrinsic size, and then it jumps in — measured at a layout shift
            of 0.19 on the artwork page. The ratio is the file's, never a
            shared shape, so this reserves the painting rather than cropping it.
          */
          <span
            className={styles.hang}
            style={{ '--painting-ratio': image.width / image.height }}
          >
            <Image
              className={styles.painting}
              src={image.src}
              alt={alt}
              width={image.width}
              height={image.height}
              sizes={sizes}
              priority={priority}
            />
          </span>
        ) : (
          <p className={styles.empty}>{emptyLabel}</p>
        )}
      </div>
    </div>
  );
}
