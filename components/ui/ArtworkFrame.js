import Image from 'next/image';
import styles from './ArtworkFrame.module.css';

/**
 * A painting hung inside a fixed-size frame.
 *
 * This component carries the project's hard layout rule: **a painting is never
 * cropped.** The frame is a fixed box at a single aspect ratio, shared by every
 * card, which is what keeps grid rows aligned. The painting sits inside it at
 * its own natural ratio, scaled down to fit entirely, centred, with padding on
 * all sides — so a tall portrait and a wide landscape occupy identical boxes
 * while both stay whole.
 *
 * The mechanism is `max-width`/`max-height: 100%` with `width`/`height: auto`
 * (plus `object-fit: contain` as a backstop) in ArtworkFrame.module.css. Do not
 * replace it with `object-fit: cover` or a fixed `fill` layout — both crop.
 *
 * `image.width` / `image.height` are the true pixel dimensions of the file,
 * generated by scripts/generate-image-manifest.mjs, never typed by hand.
 */
export default function ArtworkFrame({
  image,
  alt,
  sizes,
  priority = false,
  ratio,
  /** "surface" hangs the work on a white card; "bare" hangs it straight on the wall. */
  tone = 'surface',
  className = '',
}) {
  return (
    <div
      className={[styles.frame, styles[tone], className].filter(Boolean).join(' ')}
      /* Lets the hero opt into a wider frame without a second component. */
      style={ratio ? { '--frame-ratio': ratio } : undefined}
    >
      {/*
        The painting is centred inside an absolutely-positioned mat rather than
        laid out in normal flow. That matters: in flow, the image's intrinsic
        height wins over the frame's aspect-ratio and stretches the box, so
        cards end up different heights. Taking it out of flow makes the frame's
        height definite, which is what "fixed-size container" requires.
      */}
      <div className={styles.mat}>
        <Image
          className={styles.painting}
          src={image.src}
          alt={alt}
          width={image.width}
          height={image.height}
          sizes={sizes}
          priority={priority}
        />
      </div>
    </div>
  );
}
