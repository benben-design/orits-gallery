import Link from 'next/link';
import { notFound } from 'next/navigation';
import Container from '@/components/ui/Container';
import Section from '@/components/ui/Section';
import SectionHeading from '@/components/ui/SectionHeading';
import ButtonLink from '@/components/ui/ButtonLink';
import { getDictionary } from '@/lib/i18n/dictionaries';
import { localeHref } from '@/lib/i18n/config';
import { formatPrice } from '@/lib/format';
import { getOrderForConfirmation } from '@/lib/data/orders-repository';
import styles from './page.module.css';

/**
 * /[locale]/order/[id] — what happened to one order.
 *
 * **Reachable by the order's id and by nothing else.** That id is a v4 uuid
 * generated by the database, so it is long, random and non-sequential; there is
 * no list, no search and no account to reach it through. It is also what
 * travelled to the payment provider as `Order` and came back on the redirect,
 * which is how the return handler knows where to send somebody.
 *
 * **It reads the order's row and says what is true of it.** There is no outcome
 * carried in the URL and no flash message, which is what makes refreshing safe:
 * a buyer who reloads this page — or reaches it a week later from their history
 * — sees the same thing, because the row is the only source.
 *
 * Three states, and the middle one is the one that matters most:
 *
 * - **Confirmed.** The payment verified and the paintings are theirs.
 * - **Not confirmed.** The order exists but no verified payment ever arrived —
 *   a decline, a system error at the provider, a forged redirect, or, today,
 *   simply no credentials to verify with. It says plainly that nothing was
 *   bought and nothing was held, and what to do if a card was charged anyway.
 * - **Sold moments ago.** They paid, and somebody else got the painting in
 *   between. See the note on that block below.
 */

/** Which of the three things this page is. */
function orderState(order) {
  if (order.status === 'pending') return 'notConfirmed';

  /*
    `refundDue` is checked before the status, because such an order IS `paid` —
    money moved and the tax record needs that — and it is the column that says a
    refund is owed on top. See migration 010 for why it is not a seventh status.
  */
  if (order.refundDue || order.status === 'cancelled' || order.status === 'refunded') {
    return 'unavailable';
  }

  return 'confirmed';
}

/** Which sentence about the money belongs to an unfulfillable order. */
function moneySentence(order, copy) {
  if (order.status === 'refunded') return copy.unavailableRefunded;
  if (order.status === 'cancelled') return copy.unavailableVoided;

  return copy.unavailableRefundDue;
}

export async function generateMetadata({ params }) {
  const { locale } = await params;
  const dictionary = await getDictionary(locale);

  /*
    Never indexed, and no record data in the title. An order is per-buyer state
    with nothing to rank, and `generateMetadata` runs before anything else — a
    title built from an order would describe a stranger's purchase to whoever
    guessed the URL. seo.md keeps this path out of the sitemap for the same
    reason; this is the second half of it.
  */
  return {
    title: dictionary.orderConfirmation.title,
    robots: { index: false, follow: false },
  };
}

export default async function OrderPage({ params }) {
  const { locale, id } = await params;
  const dictionary = await getDictionary(locale);
  const copy = dictionary.orderConfirmation;

  const order = await getOrderForConfirmation(id);

  /*
    A malformed or unknown id is a 404 rather than an explanation. An order page
    that distinguished "no such order" from "not yours" would be a way to find
    out which order ids exist.
  */
  if (!order) notFound();

  const state = orderState(order);

  return (
    <Section>
      <Container>
        <div className={styles.column}>
          {state === 'confirmed' ? (
            <>
              <SectionHeading as="h1">{copy.confirmedTitle}</SectionHeading>
              <p className={styles.lead}>{copy.confirmedLead}</p>

              <Reference order={order} copy={copy} />

              <h2 className={styles.blockTitle}>{copy.itemsTitle}</h2>
              <ul className={styles.lines}>
                {order.lines.map((line) => (
                  <li key={line.workId} className={styles.line}>
                    <Link
                      href={localeHref(locale, `/art/${line.slug[locale]}`)}
                      className={styles.lineTitle}
                    >
                      {line.title[locale]}
                    </Link>
                    <span className={styles.lineAmount}>
                      <bdi>{formatPrice(line.price, locale)}</bdi>
                    </span>
                  </li>
                ))}
              </ul>

              <p className={styles.totalRow}>
                <span className={styles.totalLabel}>{copy.total}</span>
                <span className={styles.totalAmount}>
                  <bdi>{formatPrice(order.total, locale)}</bdi>
                </span>
              </p>

              {/*
                What happens next, and it differs by delivery method. The pickup
                wording names no address and no opening hours, because the artist
                has neither — collection is arranged afterwards, and a page that
                implied somewhere to turn up would be inventing a shop.
              */}
              <h2 className={styles.blockTitle}>{copy.nextTitle}</h2>
              <p className={styles.next}>
                {order.deliveryMethod === 'shipping' ? copy.nextShipping : copy.nextPickup}
              </p>
            </>
          ) : null}

          {state === 'notConfirmed' ? (
            <>
              <SectionHeading as="h1">{copy.notConfirmedTitle}</SectionHeading>
              <p className={styles.lead}>{copy.notConfirmedLead}</p>
              <p className={styles.next}>{copy.notConfirmedNext}</p>

              <Reference order={order} copy={copy} />

              <p className={styles.action}>
                <ButtonLink href={localeHref(locale, '/checkout')}>
                  {copy.notConfirmedAction}
                </ButtonLink>
              </p>
            </>
          ) : null}

          {state === 'unavailable' ? (
            /*
              They paid and cannot have it. The order of these three sentences is
              the point: what happened, then what happens to their money, then
              what they can do — because the second is the only one they are
              going to care about while they read the first.
            */
            <>
              <SectionHeading as="h1">{copy.unavailableTitle}</SectionHeading>
              <p className={styles.lead}>{copy.unavailableLead}</p>
              <p className={styles.money}>{moneySentence(order, copy)}</p>
              <p className={styles.next}>{copy.unavailableNext}</p>

              <Reference order={order} copy={copy} />

              <p className={styles.action}>
                <ButtonLink href={localeHref(locale, '/gallery')}>
                  {dictionary.cart.emptyAction}
                </ButtonLink>
              </p>
            </>
          ) : null}
        </div>
      </Container>
    </Section>
  );
}

/**
 * The order number, on every state.
 *
 * It is the only thing a buyer can quote back at us, so it is present whether
 * the news is good or bad — and it is the address of this page, so somebody who
 * has it can always return. `dir="ltr"` because a uuid is a Latin-and-digits run
 * that would otherwise be reordered inside Hebrew prose.
 */
function Reference({ order, copy }) {
  return (
    <p className={styles.reference}>
      <span className={styles.referenceLabel}>{copy.referenceLabel}</span>
      <bdi dir="ltr" className={styles.referenceValue}>
        {order.id}
      </bdi>
    </p>
  );
}
