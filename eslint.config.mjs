import { defineConfig, globalIgnores } from 'eslint/config';
import nextVitals from 'eslint-config-next/core-web-vitals';

/**
 * ESLint — flat config, the only format Next.js 16 supports. `next lint` was
 * removed in 16, so linting runs through the standard ESLint CLI: `npm run lint`.
 *
 * `core-web-vitals` rather than the base `eslint-config-next`: the rules worth
 * having here are the Next-specific ones that the base set only warns about or
 * omits — a bare <img> instead of next/image, an <a> for internal navigation
 * instead of next/link, a missing alt, sync scripts. Those are exactly the
 * mistakes that carry over from plain React.
 *
 * Deliberately NOT wired into `build` or `prebuild`. Linting is something you
 * run when you choose; an unused variable must never be able to fail a
 * deployment. See .claude/rules/setup.md.
 */
const eslintConfig = defineConfig([
  ...nextVitals,

  /**
   * Passing globalIgnores replaces eslint-config-next's own defaults rather
   * than adding to them, so the defaults are restated here alongside ours.
   */
  globalIgnores([
    // eslint-config-next's defaults.
    '.next/**',
    'out/**',
    'build/**',
    'next-env.d.ts',

    // Ours.
    'node_modules/**',
    'public/**',
    // Generated by scripts/generate-image-manifest.mjs on every build.
    // Not hand-maintained code.
    'lib/data/image-manifest.json',
  ]),
]);

export default eslintConfig;
